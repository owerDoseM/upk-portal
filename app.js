function getSelectedOptionText(select) {
  if (!select) return '';
  if (select.selectedOptions && select.selectedOptions[0]) return select.selectedOptions[0].text;
  if (select.options && select.selectedIndex >= 0 && select.options[select.selectedIndex]) return select.options[select.selectedIndex].text;
  return select.value || '';
}

